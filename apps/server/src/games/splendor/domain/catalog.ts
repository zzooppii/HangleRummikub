export function makeSplendorCards(id: () => string): SplendorCard[] {
  return ROWS.map(
    ([tier, bonus, points, white, blue, green, red, black], index) =>
      parse(SplendorCardSchema, {
        cardId: id(),
        tier,
        bonus,
        points,
        cost: {
          WHITE: white,
          BLUE: blue,
          GREEN: green,
          RED: red,
          BLACK: black,
        },
        art: (tier - 1) * 2 + (index % 2),
      }),
  );
}
